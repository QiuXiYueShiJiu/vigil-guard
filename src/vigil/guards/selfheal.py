def describe(result: dict) -> str:
    """The report block. "" when this run has nothing to say.

    Every action is reported, and every action says which file, why, what
    was done and what the recheck found. A silent auto-repair is not allowed
    here: if the program is rewriting files on the host, the operator is told
    every single time, with the four facts needed to disagree with it.
    """
    if not result:
        return ""
    if not result.get("enabled"):
        return ""
    healed = result.get("healed") or []
    unhealed = result.get("unhealed") or []
    limited = result.get("limited") or []
    unsupported = result.get("unsupported") or []
    if not (healed or unhealed or limited or unsupported):
        return ""

    lines = []
    if healed:
        lines.append("已自动重建 %d 个本程序生成的配置：" % len(healed))
        for e in healed:
            lines.append("       ✅ %s（%s）\n          做了什么：%s\n"
                         "          复检：%s"
                         % (e["path"], e["was"], e.get("means", ""),
                            e.get("detail", "")))
    if unhealed:
        lines.append("尝试重建但**未成功** %d 个：" % len(unhealed))
        for e in unhealed:
            lines.append("       ❌ %s（%s）\n          尝试：%s\n"
                         "          结果：%s"
                         % (e["path"], e["was"], e.get("means", ""),
                            e.get("detail", "")))
    if limited:
        lines.append("**反复被篡改**，已达重建上限、只报警不再重建 %d 个"
                     "（反复对改本身就是主动篡改的签名，按 CRIT 处理）："
                     % len(limited))
        for e in limited:
            lines.append("       ⏳ %s（%s，已尝试 %s/%s 次）\n          %s"
                         % (e["path"], e["was"], e.get("count", "?"),
                            e.get("max", "?"), e.get("reason", "")))
    if unsupported:
        lines.append("不在自动重建范围、只报告 %d 个：" % len(unsupported))
        for e in unsupported:
            lines.append("       ℹ️ %s（%s）\n          %s；人工处理：%s"
                         % (e["path"], e["was"], e.get("reason", ""),
                            e.get("manual", "")))
    return "\n       ".join(lines)
