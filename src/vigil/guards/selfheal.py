def heal(cfg, removed=(), changed=(), baseline=None, healstate=None,
         now: float = None, regenerators=None) -> dict:
    """Try to rebuild generated artifacts that were deleted or altered.

    Returns::

        {"enabled": bool, "attempted": int, "healed": [ {...} ],
         "unhealed": [ {...} ], "limited": [ {...} ],
         "unsupported": [ {...} ], "changed_baseline": {path: digest},
         "baseline": {path: digest}}

    ``changed_baseline`` is the caller's instruction to advance its stored
    digest for the paths that came back: the next run must not re-report a
    file this run has already proven restored, or every later run would burn
    another attempt from the rate limiter on a file that is fine.

    ``baseline`` is the digest map from the last good run, used the only way
    it can be used safely: to check the rebuilt bytes against what we expect
    them to be. A rebuild that does not produce the expected content is *not*
    reported as a success -- it is reported as "written but different", which
    is the honest answer and the one that keeps a tampered environment from
    being silently blessed.
    """
    cfg_ = cfg
    enabled = _bool(cfg_, "checks.self_integrity.auto_recover", True)
    window = _int_cfg(cfg_, "checks.self_integrity.heal_window_seconds",
                      DEFAULT_HEAL_WINDOW, minimum=1)
    maximum = _int_cfg(cfg_, "checks.self_integrity.heal_max_attempts",
                       DEFAULT_HEAL_MAX, minimum=1)
    now = time.time() if now is None else float(now)
    baseline = {str(k): v for k, v in (baseline or {}).items()}
    healstate = healstate if isinstance(healstate, dict) else {}
    cache = _SpecCache()
    regs = regenerators if regenerators is not None else _registry(cache)

    removed = [str(p) for p in removed]
    changed = [str(p) for p in changed]
    out = {"enabled": enabled, "attempted": 0, "healed": [], "unhealed": [],
           "limited": [], "unsupported": [], "changed_baseline": {},
           "baseline": dict(baseline), "window": window, "max": maximum}
    if not enabled:
        return out

    # Deterministic order: the report is a rollout of what happened, and two
    # runs over the same finding should read the same.
    for path in sorted(set(removed) | set(changed)):
        was = "被删除" if path in removed else "被修改"
        action = action_for(path)
        if not action or action not in regs:
            hint = _manual_hint(path)
            out["unsupported"].append({
                "path": path, "was": was, "action": action,
                "reason": "该文件不在可自动重建的范围内（会覆盖你手改过的内容"
                          "或运行时数据），只报告不重建",
                "manual": hint})
            continue
        if not attempt_allowed(healstate, path, now=now, window=window,
                               maximum=maximum):
            tried = len((healstate.get(path) or {}).get("attempts") or [])
            out["limited"].append({
                "path": path, "was": was, "action": action,
                "count": tried, "max": maximum, "window": window,
                "reason": "%d 秒内已尝试重建 %d 次（上限 %d 次）—— 同一文件被"
                          "**反复%s**不是普通故障，而是有人在持续对抗本程序："
                          "继续重建只会陷入「重建→又被删→再重建」的循环，"
                          "并且会把「有东西正在动这个文件」这件事掩盖掉。"
                          "已改为只报警。请人工排查是谁在动它（auditd 有记录）。"
                          % (window, tried, maximum,
                             "删除" if path in removed else "修改")})
            continue

        record_attempt(healstate, path, now=now, window=window)
        out["attempted"] += 1
        # The content on disk *before* the rebuild. Read here because the
        # rebuild is about to destroy it, and the difference between the two
        # is the only record of what the tampering actually did -- which
        # rules it weakened. Read for the changed case only: a deleted file
        # has nothing to compare against.
        before_text = _read_text(path) if path in changed else None
        try:
            res = regs[action](path) or {}
        except Exception as exc:                            # noqa: BLE001
            # A regenerator that raises must not take the inspection down;
            # `safe_run` would turn it into a WARN about the wrong thing.
            res = {"ok": False, "detail": "重建过程异常：%s: %s"
                                          % (type(exc).__name__, exc)}

        # The recheck: is the expected content now on disk, and does it match
        # the baseline we were holding? Kept in its own function because the
        # "rebuilt but different" branch is the one that decides whether this
        # feature tells the truth, and it is worth testing on its own.
        entry = _recheck(path, was, action, res, baseline, cache,
                         before_text=before_text)
        if entry.pop("healed"):
            out["healed"].append(entry)
            out["changed_baseline"][path] = entry["actual"]
        else:
            out["unhealed"].append(entry)

    # Forget counters for paths that are no longer in the finding, so the
    # state file cannot grow one entry per file forever.
    live = set(removed) | set(changed)
    for stale in [p for p in list(healstate) if p not in live]:
        healstate.pop(stale, None)
    return out


def _read_text(path):
    """The file's text, or ``None`` when it cannot be read."""
    try:
        with open(str(path), "r", encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except OSError:
        return None


def _recheck(path: str, was: str, action: str, res: dict, baseline: dict,
             cache=None, before_text=None) -> dict:
    """Decide whether a rebuild actually restored *path*.

    Three outcomes, and the middle one is the whole point:

    * the file is back and its content equals the digest we had for it when
      it was known good  -> a real recovery;
    * the file is back but its content *differs* from that digest, or does
      not match what this program renders from the current configuration
      -> **not a recovery**. Reporting it as one would bless whatever
      changed the inputs, which is exactly how a silent rollback hides an
      intrusion. Reported as a failure with both digests, for a human;
    * the file is still unreadable -> a failure.
    """
    from .checks.selfcheck import digest_file

    expect, render_err = render(path, cache=cache)
    actual = digest_file(path)
    entry = {"path": path, "was": was, "action": action,
             "means": _ACTION_LABEL.get(action, action),
             "detail": res.get("detail", ""),
             "expected": "", "actual": actual, "healed": False}

    if not res.get("ok"):
        return entry
    if actual == "missing" or str(actual).startswith(("unreadable", "too-big")):
        entry["detail"] = "%s；复检仍读不到该文件（%s）" % (
            res.get("detail", ""), actual)
        return entry
    if render_err:
        # Could not compute the expected content independently. The module's
        # own installer reported success and the file is present, so this is
        # called a rebuild -- with the limitation spelled out rather than
        # silently upgraded to "verified".
        entry["healed"] = True
        entry["detail"] = "%s；复检：文件已存在（无法独立核对内容：%s）" % (
            res.get("detail", ""), render_err)
        return entry

    # The intent is in the difference, so it is recorded before anything else
    # can discard it. `expect` is what the file *should* be; `before_text` is
    # what the tampering left behind.
    diff = _weakened(before_text, expect) if before_text is not None else ""
    if diff:
        entry["detail"] = "%s；差异摘要：%s" % (entry["detail"], diff)

    entry["expected"] = _digest_text(expect)
    held = baseline.get(path)
    if held and not str(held).startswith(("missing", "unreadable", "too-big")) \
            and entry["expected"] != held:
        entry["detail"] = (
            "%s；复检：文件已重新生成，但内容与基线不一致"
            "（基线 %s… / 现在渲染出 %s…）。这说明它的输入（配置或实例状态）"
            "也已经变了，请人工核对，不要直接接受。" % (
                res.get("detail", ""), str(held)[:12],
                str(entry["expected"])[:12]))
        return entry

    entry["healed"] = True
    if not held:
        entry["detail"] = ("%s；基线里没有它的哈希（上次记录之后就消失了），"
                           "已按重新生成的内容更新基线" % res.get("detail", ""))
    else:
        entry["detail"] = ("%s；复检：内容与基线一致，已确认恢复"
                           % res.get("detail", ""))
    return entry


def _digest_text(text: str) -> str:
    import hashlib
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _bool(cfg, key: str, default: bool) -> bool:
    try:
        value = cfg.get(key, default)
    except AttributeError:                                  # pragma: no cover
        return default
    if isinstance(value, str):
        return value.strip().lower() in ("1", "true", "yes", "on")
    return bool(default if value is None else value)


