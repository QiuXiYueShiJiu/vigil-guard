def _int_cfg(cfg, key: str, default: int, minimum: int = 0) -> int:
    try:
        value = int(cfg.get(key, default))
    except (TypeError, ValueError, AttributeError):
        value = default
    return max(minimum, value)


def attempt_allowed(healstate: dict, path: str, now: float = None,
                    window: int = DEFAULT_HEAL_WINDOW,
                    maximum: int = DEFAULT_HEAL_MAX) -> bool:
    """May we try *path* again yet?

    Counted over a sliding window rather than per hour bucket: a bucket lets
    a badly-timed loop fire twice in two seconds across a boundary, which is
    exactly the loop this is here to bound.
    """
    now = time.time() if now is None else float(now)
    rec = healstate.get(path)
    if not isinstance(rec, dict):
        return True
    stamps = [float(t) for t in (rec.get("attempts") or [])
              if isinstance(t, (int, float))]
    recent = [t for t in stamps if now - t < max(1, int(window))]
    return len(recent) < max(1, int(maximum))


def record_attempt(healstate: dict, path: str, now: float = None,
                   window: int = DEFAULT_HEAL_WINDOW) -> None:
    """Count one attempt, before it is made.

    Recorded first on purpose: an attempt that hangs or crashes still
    consumed a rebuild, and a counter that only advances on success turns a
    crash-looping regenerator into an unbounded one.
    """
    now = time.time() if now is None else float(now)
    rec = healstate.setdefault(path, {})
    if not isinstance(rec, dict):
        rec = {}
        healstate[path] = rec
    stamps = [float(t) for t in (rec.get("attempts") or [])
              if isinstance(t, (int, float))]
    stamps = [t for t in stamps if now - t < max(1, int(window))]
    stamps.append(now)
    rec["attempts"] = stamps
    rec["last"] = now


