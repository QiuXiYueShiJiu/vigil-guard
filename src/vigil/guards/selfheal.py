def _write_atomic(path, text: str, mode: int = 0o644) -> None:
    from ..gates.installer import _atomic_write
    _atomic_write(path, text, mode)


def _nginx_ok() -> tuple:
    from ..gates import shield
    return shield._nginx_test()


def _nginx_reload() -> None:
    """Reload nginx the same way every other part of this program does.

    A reload is attempted only after ``nginx -t`` has accepted the file, so
    the worst case here is a reload that does not take effect -- which the
    ``runtime_config`` check will report on its own.
    """
    from ..core import detect
    binary = (detect.nginx() or {}).get("binary", "")
    if binary:
        shell.run([binary, "-s", "reload"], timeout=20)


def _regen_shield(path: str) -> dict:
    """Re-run the shield installer.

    ``shield.install`` already has the property this module needs: it writes
    atomically, runs ``nginx -t``, and rolls every byte back if the test
    fails. Reusing it is deliberate -- a second implementation of "write the
    shield safely" would drift from the first, and the drift would show up as
    nginx refusing to load.
    """
    from ..gates import shield
    res = shield.install()
    ok = bool(res.get("ok"))
    detail = ""
    if ok:
        detail = "shield.install 已重写 %s" % path
        if res.get("written"):
            detail += "（写入 %d 个文件）" % len(res["written"])
    else:
        bits = list(res.get("problems") or [])
        if res.get("refused"):
            bits.insert(0, "拒绝：会改动正在生效的 limit_req_zone 键")
        detail = "shield.install 未能完成：%s" % ("；".join(bits) or "原因未知")
    return {"ok": ok, "detail": detail}


def _gate_specs():
    """Every gate instance currently discoverable on this host."""
    from .. import gates
    try:
        return gates.detect_all() or []
    except Exception:                                       # noqa: BLE001
        return []


class _SpecCache:
    """One gate discovery per heal run.

    ``detect_all`` shells out to ``nginx -T``; calling it once per artifact
    would turn a five-file finding into five nginx dumps. The cache is an
    object rather than a module global so two concurrent runs cannot share
    (and therefore cannot stale) each other's view of the host.
    """

    def __init__(self):
        self._done = False
        self._specs = []

    def get(self) -> list:
        if not self._done:
            self._specs = _gate_specs()
            self._done = True
        return self._specs

    def set(self, specs) -> None:
        self._specs = list(specs or [])
        self._done = True


def _resolve_specs(specs, cache) -> list:
    """The instance list to work from: explicit, cached, or freshly read."""
    if specs is not None:
        return list(specs)
    if cache is not None:
        return cache.get()
    return _gate_specs()


def _gate_for_path(path: str, specs=None, cache=None):
    """The gate instance that owns *path*, or ``None``.

    Matched two ways, and both are needed. When the file still exists,
    ``spec.nginx_conf`` points straight at it. When it was *deleted* --
    the case that started this -- detection cannot find it, so the expected
    file name is rebuilt from the instance's slug and compared in the same
    directory. Never a substring match: instance ``log`` must not be able to
    claim instance ``login``'s wiring.
    """
    target = Path(path)
    specs = _resolve_specs(specs, cache)
    for spec in specs:
        if spec.nginx_conf and Path(spec.nginx_conf) == target:
            return spec
    for spec in specs:
        expected = "vigil-gate-%s.conf" % spec.slug
        if target.name == expected:
            return spec
    return None


def _regen_gate_nginx(path: str, specs=None, cache=None) -> dict:
    """Rewrite one gate's nginx snippet, prove nginx still loads, keep it.

    Deliberately **not** ``gates.install()``: that writes the gate's whole
    state directory and re-applies the operator's app patches, which is far
    more than "put this deleted snippet back". Only the snippet is written
    here, and only after ``nginx -t`` accepts it.
    """
    spec = _gate_for_path(path, specs, cache)
    if spec is None:
        return {"ok": False,
                "detail": "找不到该片段对应的网关实例，无法确定它应该是什么内容"}
    try:
        from ..gates import installer, shield
        wanted = installer.render_nginx(spec)
    except Exception as exc:                                # noqa: BLE001
        return {"ok": False, "detail": "渲染失败：%s: %s"
                                       % (type(exc).__name__, exc)}
    if not wanted.strip():
        return {"ok": False, "detail": "渲染结果为空，拒绝写入（空片段会让站点失去防护）"}

    # The v3.2.3 guard, applied *before* a single byte is written: nginx
    # accepts a changed `limit_req_zone` key on disk and refuses it on every
    # reload, so a "repair" that redefines a live zone would take the
    # protection down while looking successful. Repairing a file must never
    # reintroduce the incident this program was just fixed for, so the same
    # check the installer uses runs here too.
    zones_file = Path(getattr(spec, "zones_file", "") or (
        Path(str(path)).parent / ("vigil-gate-%s-zones.conf"
                                  % re.sub(r"\W+", "_", spec.slug))))
    try:
        if zones_file.is_file():
            previous = shield.parse_zone_definitions(
                zones_file.read_text(encoding="utf-8", errors="replace"))
            changes = shield.zone_key_changes(wanted, previous)
            if changes:
                return {"ok": False,
                        "detail": "拒绝重建：这会改动正在生效的 limit_req_zone 键，"
                                  "nginx 会拒绝任何 reload —— %s"
                                  % shield.describe_zone_conflicts(changes)}
    except OSError as exc:
        return {"ok": False, "detail": "无法读取限流区文件，保守起见不重建：%s" % exc}

    old = None
    try:
        if os.path.isfile(path):
            with open(path, "r", encoding="utf-8", errors="replace") as fh:
                old = fh.read()
        _write_atomic(path, wanted, 0o644)
    except OSError as exc:
        return {"ok": False, "detail": "写入失败：%s" % exc}

    ok, out = _nginx_ok()
    if not ok:
        # Put the host back exactly as it was. A snippet that nginx refuses
        # takes every site on the machine down, which is a far worse outcome
        # than a missing snippet.
        try:
            if old is None:
                Path(path).unlink(missing_ok=True)
            else:
                _write_atomic(path, old, 0o644)
        except OSError:
            pass
        _nginx_ok()
        return {"ok": False,
                "detail": "nginx 拒绝重新生成的片段，已还原：%s" % str(out)[-200:]}

    _nginx_reload()
    detail = "已重新生成并写入 %s（%d 字节）" % (path, len(wanted))
    weakened = _weakened(old, wanted)
    if weakened:
        detail += "；" + weakened
    return {"ok": True, "detail": detail}


def _regen_gate_lua(path: str, specs=None, cache=None) -> dict:
    """Rebuild ``gate.lua`` from the instance's live spec.

    Safe to rebuild where ``config.php`` is not: the Lua file is pure
    template output -- every value it interpolates is also stored in
    ``policy.conf``, it is never hand-edited, and it is not an input to its
    own render. Its expected content is known *before* anything is written,
    so a mismatch against the baseline is caught without writing at all.
    """
    state_dir = str(Path(path).parent)
    spec = None
    for cand in _resolve_specs(specs, cache):
        if str(cand.state_dir).rstrip("/") == state_dir.rstrip("/"):
            spec = cand
            break
    if spec is None:
        return {"ok": False, "detail": "找不到该文件所属的网关实例（%s）" % state_dir}
    try:
        from ..gates import installer
        text = installer.render_files(spec)[Path(path)][0]
    except Exception as exc:                                # noqa: BLE001
        return {"ok": False, "detail": "渲染失败：%s: %s"
                                       % (type(exc).__name__, exc)}
    try:
        _write_atomic(path, text, 0o640)
    except OSError as exc:
        return {"ok": False, "detail": "写入失败：%s" % exc}
    return {"ok": True, "detail": "已重新生成 %s（%d 字节）" % (path, len(text))}


def _weakened(before_text, expected_text) -> str:
    """What the tampering took away, as a one-line summary.

    The direction is the whole point: **expected minus before**. A line that
    is in the file this program would write but is *not* in the file that was
    found is a protection that was removed -- the `deny` that was deleted, the
    `access_by_lua_file` that was unhooked, the rate limit that was dropped.
    Those are exactly the lines the rebuild puts back, and they are the only
    part of the difference that says anything about intent.

    Lines that are only in the tampered file are *additions*, and they are not
    reported here: an addition to a generated file cannot survive the rebuild
    anyway, so naming it would be noise (and reporting it as "weakened" would
    be wrong). ``before_text is None`` means there was nothing to compare
    against -- a deleted file -- and gives ``""``.

    Only directive-looking lines are named, and only a handful: a full diff of
    an nginx snippet is noise, and a summary nobody reads is the same as none.
    """
    if before_text is None:
        return ""
    before = set(str(before_text).splitlines())
    expected = set(str(expected_text).splitlines())
    gone = [line.strip() for line in (expected - before) if line.strip()]
    if not gone:
        return ""
    interesting = [line for line in gone if _DIRECTIVE_RX.match(line)]
    shown = interesting or gone
    head = "；".join(shown[:4])
    if len(shown) > 4:
        head += " …… 共 %d 行" % len(shown)
    kind = "被削弱的规则" if interesting else "被改动的行"
    return "%s（%d 行，重建后已恢复）：%s" % (kind, len(shown), head)


#: Directives whose disappearance is a security change worth naming. Kept
#: broad on purpose: a directive we do not list is still counted in the
#: total, it just does not get named individually.
_DIRECTIVE_RX = re.compile(
    r"^(?:deny|allow|limit_req|limit_conn|limit_rate|return|rewrite|proxy_pass"
    r"|access_by_lua_file|auth_basic|ssl_|add_header|include|if|location"
    r"|server_name|listen|error_page|internal)\b")


def _registry(cache=None) -> dict:
    """Action name -> regenerator. Built at call time, not import time, so
    the seam is cheap to replace in tests.

    The gate actions are wrapped so they share the run's single discovery of
    the host's gate instances (see :class:`_SpecCache`).
    """
    return {
        "shield": _regen_shield,
        "gate_nginx": lambda path: _regen_gate_nginx(path, cache=cache),
        "gate_lua": lambda path: _regen_gate_lua(path, cache=cache),
    }


def render(path: str, cache=None) -> tuple:
    """What this module *would* write for *path*, without writing.

    Returns ``(text, err)``. Used to check a rebuild against the stored
    baseline before touching the disk, and kept separate from the writers so
    a caller can never accidentally get one when it wanted the other.
    """
    action = action_for(path)
    if action == "shield":
        from ..gates import shield
        try:
            return shield.render_shield(), ""
        except Exception as exc:                            # noqa: BLE001
            return "", "%s: %s" % (type(exc).__name__, exc)
    if action == "gate_nginx":
        spec = _gate_for_path(path, cache=cache)
        if spec is None:
            return "", "找不到该片段对应的网关实例"
        from ..gates import installer
        return installer.render_nginx(spec), ""
    if action == "gate_lua":
        state_dir = str(Path(path).parent)
        for cand in _resolve_specs(None, cache):
            if str(cand.state_dir).rstrip("/") == state_dir.rstrip("/"):
                from ..gates import installer
                return installer.render_files(cand)[Path(path)][0], ""
        return "", "找不到该文件所属的网关实例"
    return "", "没有可用的重建方式"


